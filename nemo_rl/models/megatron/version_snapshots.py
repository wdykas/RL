"""Weight-version snapshots for version-point gradients (``grpo.async_grpo.version_point_gradient``).

Async GRPO trains on rollouts generated by an older weight version theta_g. A version-point
gradient computes the forward/backward at theta_g itself and lets the optimizer step the
current weights theta_t with it. This module keeps the weights of every version the replay
buffer can still reference and swaps one of them into the live Megatron model.

Layout. Each rank keeps a plain copy (pinned host memory) of its own data-parallel shard of
every DDP param bucket: exactly what the distributed optimizer owns and what a param
all-gather publishes. A swap-in saves the current shards on the GPU (1 / DP of the local
params), writes the snapshot into them and all-gathers; a swap-out writes the saved shards
back and all-gathers again. Both directions are bitwise: the full param buffers are the
all-gather of the shards before and after. Every rank swaps its own shards, so tensor and
expert parallelism need nothing extra.

Two storage modes:

- ``VersionSnapshots`` (``full``): one host copy of the shards per kept version.
- ``SparseDiffVersionSnapshots`` (``sparse_diff``): one host copy of the newest version (the
  current weights at training time) plus, per older version k, the reverse diff from
  version k + 1: the flat index and old value of every word an optimizer step changed. A
  version is rebuilt on the GPU from the current shards by applying the diffs newest first,
  so the oldest value of an index changed in several steps wins. Exact (bitwise) by
  construction; host memory is about one shard plus 3 x (changed fraction) x shard per
  kept bf16 version (int32 index + bf16 value per changed word).
"""

import time
from contextlib import contextmanager
from typing import Any, Callable, Iterator, Optional

import torch


def ddp_local_param_shards(model) -> list[torch.Tensor]:
    """This rank's shard of every param bucket of a Megatron ``DistributedDataParallel`` model.

    These are the slices the distributed optimizer updates and ``start_param_sync`` all-gathers.
    """
    shards = []
    for group in list(model.bucket_groups) + list(model.expert_parallel_bucket_groups):
        size = group.intra_distributed_optimizer_instance_size
        rank = group.intra_distributed_optimizer_instance_rank
        for bucket in group.buckets:
            data = bucket.param_data
            shard_size = data.numel() // size
            shards.append(data[rank * shard_size : (rank + 1) * shard_size])
    return shards


def _bits(t: torch.Tensor) -> torch.Tensor:
    """Integer view of a tensor's raw bits (bitwise comparison, NaN payloads included)."""
    return t.view({1: torch.uint8, 2: torch.int16, 4: torch.int32}[t.element_size()])


class VersionSnapshots:
    """Host snapshots of this rank's param shards per weight version, swappable into the model.

    ``local_shards()`` returns this rank's shards of the param buffers and ``sync()``
    all-gathers the full params from them. ``keep_versions`` newest versions are kept; older
    ones are evicted when a newer snapshot is taken. While a version is swapped in, the
    current params must not change (the optimizer steps after the swap-out).
    """

    def __init__(
        self,
        local_shards: Callable[[], list[torch.Tensor]],
        sync: Callable[[], None],
        keep_versions: int,
        cached_weight_modules: list[torch.nn.Module],
    ):
        if keep_versions < 1:
            raise ValueError(f"keep_versions must be >= 1, got {keep_versions}.")
        self.local_shards = local_shards
        self.sync = sync
        self.keep_versions = keep_versions
        # Modules that cache per-weight state across microbatches (TE FP8 weight casts).
        self._cached_weight_modules = cached_weight_modules
        self.snapshots: dict[int, list[torch.Tensor]] = {}
        self._saved_current: list[torch.Tensor] = []
        # Seconds the last swap-in took (rebuild + all-gather), and the changed fraction of
        # the newest step (sparse_diff only).
        self.last_swap_in_s = 0.0
        self.last_diff_frac = float("nan")

    def _host_copy(self, t: torch.Tensor) -> torch.Tensor:
        pin = torch.cuda.is_available()  # pageable only in CPU-only unit tests
        return torch.empty(t.shape, dtype=t.dtype, pin_memory=pin).copy_(t)

    @torch.no_grad()
    def snapshot(self, version: int) -> bool:
        """Keep this rank's shards of the current weights as ``version``; evict the oldest.

        A version that already has a snapshot (restored from a checkpoint) is compared
        instead: if the current weights differ in any bit, the version is dropped (its batches
        take the IS path) and False is returned.
        """
        if self._saved_current:
            raise RuntimeError("snapshot() while a version is swapped in.")
        self.sync()
        shards = self.local_shards()
        if version in self.snapshots:
            same = all(
                torch.equal(_bits(saved), _bits(shard.cpu()))
                for saved, shard in zip(self.snapshots[version], shards)
            )
            if not same:
                del self.snapshots[version]
            return same
        self.snapshots[version] = [self._host_copy(shard) for shard in shards]
        for old in sorted(self.snapshots)[: -self.keep_versions]:
            del self.snapshots[old]
        return True

    def has(self, version: int) -> bool:
        return version in self.snapshots

    def versions(self) -> list[int]:
        return sorted(self.snapshots)

    def stored_bytes(self) -> int:
        """Host bytes held by the snapshots."""
        return sum(
            t.numel() * t.element_size() for v in self.snapshots.values() for t in v
        )

    def _invalidate_weight_caches(self) -> None:
        for module in self._cached_weight_modules:
            module.is_first_microbatch = True

    def _write_version(self, shards: list[torch.Tensor], version: int) -> None:
        """Overwrite the (current) shards with the weights of ``version``."""
        for shard, saved in zip(shards, self.snapshots[version]):
            shard.copy_(saved, non_blocking=True)

    @contextmanager
    def swapped_in(self, version: int) -> Iterator[None]:
        """Hold the weights of ``version`` in the param buffers while inside; restore bitwise on exit."""
        if not self.has(version):
            raise KeyError(f"No snapshot of weight version {version}.")
        if self._saved_current:
            raise RuntimeError("A version is already swapped in.")
        start = time.perf_counter()
        with torch.no_grad():
            self.sync()  # the buffers hold exactly the all-gather of the current shards
            shards = self.local_shards()
            self._saved_current = [shard.clone() for shard in shards]
        try:
            with torch.no_grad():
                self._write_version(shards, version)
                self.sync()
                self._invalidate_weight_caches()
            if torch.cuda.is_available():
                torch.cuda.synchronize()
            self.last_swap_in_s = time.perf_counter() - start
            yield
        finally:
            with torch.no_grad():
                for shard, saved in zip(self.local_shards(), self._saved_current):
                    shard.copy_(saved)
                self._saved_current = []
                self.sync()
                self._invalidate_weight_caches()

    def _check_shapes(self, tensors: list[torch.Tensor], what: str) -> None:
        shapes = [(s.shape, s.dtype) for s in self.local_shards()]
        if [(t.shape, t.dtype) for t in tensors] != shapes:
            raise ValueError(
                f"{what} does not match this rank's param shards (different parallel layout?)."
            )

    def checkpoint_items(self) -> Iterator[tuple[str, Any]]:
        """(name, object) pairs to save with a checkpoint, one file each."""
        for version in self.versions():
            yield f"version_{version}", self.snapshots[version]

    def load_checkpoint_item(self, name: str, obj: Any) -> None:
        """Restore one item saved by ``checkpoint_items`` (one at a time bounds host memory)."""
        kind, _, version = name.rpartition("_")
        if kind != "version":
            raise ValueError(f"Unexpected snapshot item {name!r} for full snapshots.")
        self._check_shapes(obj, f"Snapshot of version {version}")
        self.snapshots[int(version)] = [self._host_copy(t) for t in obj]
        for old in sorted(self.snapshots)[: -self.keep_versions]:
            del self.snapshots[old]

    def finish_load(self) -> None:
        """Called after every checkpoint item was loaded."""


class SparseDiffVersionSnapshots(VersionSnapshots):
    """The newest version as a full host copy plus reverse diffs for the older versions.

    ``diffs[k]`` turns the shards of version k + 1 into those of version k: per shard, the
    flat indices of the words that differ and their values in version k. Versions are
    expected to be snapshotted in order (one per optimizer step); a gap drops the chain.
    The current weights must equal the newest version whenever a version is swapped in
    (true at training time: the snapshot is taken at each refit, and the weights do not
    change until the next optimizer step). ``check=True`` (debug) also keeps full copies
    and verifies every rebuild against them bitwise.
    """

    _CHUNK = 1 << 26  # words compared per GPU chunk

    def __init__(
        self,
        local_shards: Callable[[], list[torch.Tensor]],
        sync: Callable[[], None],
        keep_versions: int,
        cached_weight_modules: list[torch.nn.Module],
        check: bool,
    ):
        super().__init__(local_shards, sync, keep_versions, cached_weight_modules)
        self.base_version: Optional[int] = None
        self.base: list[torch.Tensor] = []
        self.diffs: dict[int, list[tuple[torch.Tensor, torch.Tensor]]] = {}
        self.check = check
        self.checks_passed = 0
        # Full-mode items loaded from a checkpoint, converted in finish_load().
        self._loaded_full: dict[int, list[torch.Tensor]] = {}

    @torch.no_grad()
    def _reverse_diff(
        self, base: torch.Tensor, shard: torch.Tensor
    ) -> tuple[torch.Tensor, torch.Tensor]:
        """(indices, old values) of the words where ``base`` (host, old) and ``shard`` differ; updates ``base``."""
        index_dtype = torch.int32 if shard.numel() < 2**31 else torch.int64
        indices, values = [], []
        for start in range(0, shard.numel(), self._CHUNK):
            cur = shard[start : start + self._CHUNK]
            old = base[start : start + self._CHUNK].to(cur.device, non_blocking=True)
            changed = (_bits(old) != _bits(cur)).nonzero().squeeze(1)
            indices.append((changed + start).to(index_dtype).cpu())
            values.append(old[changed].cpu())
            base[start : start + self._CHUNK].copy_(cur)
        return self._host_copy(torch.cat(indices)), self._host_copy(torch.cat(values))

    @torch.no_grad()
    def snapshot(self, version: int) -> bool:
        if self._saved_current:
            raise RuntimeError("snapshot() while a version is swapped in.")
        self.sync()
        shards = self.local_shards()
        if version == self.base_version:
            same = all(
                torch.equal(_bits(saved), _bits(shard.cpu()))
                for saved, shard in zip(self.base, shards)
            )
            if not same:
                self.base_version, self.base, self.diffs = None, [], {}
                self.snapshots = {}
            return same
        if self.base_version is not None and version == self.base_version + 1:
            diff = [self._reverse_diff(b, s) for b, s in zip(self.base, shards)]
            self.diffs[self.base_version] = diff
            changed = sum(i.numel() for i, _ in diff)
            self.last_diff_frac = changed / max(1, sum(s.numel() for s in shards))
        else:  # first snapshot, or a gap: start a new chain
            self.diffs = {}
            self.base = [self._host_copy(shard) for shard in shards]
        self.base_version = version
        for old in [k for k in self.diffs if k <= version - self.keep_versions]:
            del self.diffs[old]
        if self.check:
            self.snapshots[version] = [self._host_copy(shard) for shard in shards]
            for old in sorted(self.snapshots)[: -self.keep_versions]:
                del self.snapshots[old]
        return True

    def has(self, version: int) -> bool:
        if self.base_version is None or version > self.base_version:
            return False
        return all(k in self.diffs for k in range(version, self.base_version))

    def versions(self) -> list[int]:
        if self.base_version is None:
            return []
        return [
            v
            for v in range(
                min(self.diffs, default=self.base_version), self.base_version + 1
            )
            if self.has(v)
        ]

    def stored_bytes(self) -> int:
        tensors = list(self.base) + [
            t for d in self.diffs.values() for p in d for t in p
        ]
        return (
            sum(t.numel() * t.element_size() for t in tensors) + super().stored_bytes()
        )

    def _write_version(self, shards: list[torch.Tensor], version: int) -> None:
        for k in range(
            self.base_version - 1, version - 1, -1
        ):  # newest first: oldest value wins
            for shard, (indices, values) in zip(shards, self.diffs[k]):
                shard[indices.to(shard.device, non_blocking=True).long()] = values.to(
                    shard.device, non_blocking=True
                )
        if self.check and version in self.snapshots:
            for shard, full in zip(shards, self.snapshots[version]):
                if not torch.equal(_bits(shard.cpu()), _bits(full)):
                    raise RuntimeError(
                        f"Sparse-diff rebuild of version {version} differs from its full snapshot."
                    )
            self.checks_passed += 1

    def checkpoint_items(self) -> Iterator[tuple[str, Any]]:
        if self.base_version is None:
            return
        yield f"base_{self.base_version}", self.base
        for k in sorted(self.diffs):
            yield f"diff_{k}", [list(pair) for pair in self.diffs[k]]

    def load_checkpoint_item(self, name: str, obj: Any) -> None:
        kind, _, version = name.rpartition("_")
        if kind == "base":
            self._check_shapes(obj, f"Base snapshot of version {version}")
            self.base = [self._host_copy(t) for t in obj]
            self.base_version = int(version)
        elif kind == "diff":
            self.diffs[int(version)] = [
                (self._host_copy(i), self._host_copy(v)) for i, v in obj
            ]
        elif kind == "version":  # a checkpoint written in full mode
            self._check_shapes(obj, f"Snapshot of version {version}")
            self._loaded_full[int(version)] = obj
        else:
            raise ValueError(
                f"Unexpected snapshot item {name!r} for sparse_diff snapshots."
            )

    @torch.no_grad()
    def finish_load(self) -> None:
        """Convert full-mode snapshots from the checkpoint into a base plus reverse diffs."""
        if not self._loaded_full:
            return
        versions = sorted(self._loaded_full)
        newest = self._loaded_full[versions[-1]]
        self.base_version = versions[-1]
        self.base = [self._host_copy(t) for t in newest]
        self.diffs = {}
        for older, newer in zip(versions[:-1], versions[1:]):
            if newer != older + 1:
                self.diffs = {}  # only a contiguous chain ending at the newest version
                continue
            diff = []
            for old, new in zip(self._loaded_full[older], self._loaded_full[newer]):
                changed = (_bits(old) != _bits(new)).nonzero().squeeze(1)
                index_dtype = torch.int32 if old.numel() < 2**31 else torch.int64
                diff.append(
                    (
                        self._host_copy(changed.to(index_dtype)),
                        self._host_copy(old[changed]),
                    )
                )
            self.diffs[older] = diff
        if self.check:
            self.snapshots = {
                v: [self._host_copy(t) for t in self._loaded_full[v]] for v in versions
            }
        self._loaded_full = {}
